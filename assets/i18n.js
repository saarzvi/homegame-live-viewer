const languages = ["he", "en", "ar"];
function defaultCode() {
  const browser = navigator.language?.slice(0, 2)?.toLowerCase();
  return languages.includes(browser) ? browser : "he";
}
let language = defaultCode();
try {
  const chosen = localStorage.getItem("homeGameViewerLanguage");
  if (languages.includes(chosen)) language = chosen;
} catch {}
export function getLanguage() { return language; }
export function tr(key) { return locales[language][key] ?? locales.he[key] ?? key; }
export function setLanguage(code) {
  if (!languages.includes(code)) return;
  language = code;
  try { localStorage.setItem("homeGameViewerLanguage", code); } catch {}
}
export function localeCode() {
  return language === "ar" ? "ar-IL" : language === "en" ? "en-IL" : "he-IL";
}
export function applyLanguage() {
  document.documentElement.lang = language;
  document.documentElement.dir = language === "en" ? "ltr" : "rtl";
  document.title = "Home Game · " + tr("title");
  const picker = document.getElementById("language-picker");
  if (picker) picker.value = language;
  for (const node of document.querySelectorAll("[data-i18n]")) {
    const k = node.getAttribute("data-i18n");
    node.textContent = tr(k);
  }
}
